export function buildDemoJob(): JobResult {
  const verified = normalizeVerified(PACKET);
  const checks: VerificationCheck[] = verified.verification.checks.map((check) => {
    const special = NOTES[check.id];
    if (special) {
      return { ...check, confidence: special.confidence, note: special.note };
    }
    if (check.status === "corrected") return check;
    return { ...check, confidence: "high", note: null };
  });
  const tooling = finalizeTooling(TOOLS, [HAAS_ENDMILL]);
  return {
    analysis: verified.analysis,
    verification: { ...verified.verification, checks },
    hardFeatures: verified.hardFeatures,
    tooling: tooling.items,
    toolingNote:
      "Demo catalog links. The 1/2 inch end mill points at a real Haas Tooling product page (03-0393). Every other link is a catalog search, not an exact match.",
    warnings: [],
    generatedLabel: "Sample job",
    demo: true,
  };
}
